#!/bin/bash

validate_params() {
    # Проверка наличия всех параметров
    if [ -z "$FOLDER_LETTERS" ] || [ -z "$FILE_NAME_EXT" ] || [ -z "$FILE_SIZE" ]; then
        echo "Ошибка: необходимо указать 3 параметра"
        echo "Пример: ./main.sh az az.az 3Mb"
        exit 1
    fi
    
    # Проверка длины букв для папок
    if [ ${#FOLDER_LETTERS} -gt 7 ]; then
        echo "Ошибка: для названия папок не более 7 символов"
        exit 1
    fi
    
    # Проверка, что буквы только английские для папок
    if [[ ! "$FOLDER_LETTERS" =~ ^[a-zA-Z]+$ ]]; then
        echo "Ошибка: буквы для папок должны быть английскими"
        exit 1
    fi
    
    # Проверка формата параметра 2 (имя.расширение)
    if [[ ! "$FILE_NAME_EXT" =~ ^[a-zA-Z]+\.[a-zA-Z]+$ ]]; then
        echo "Ошибка: параметр 2 должен быть в формате имя.расширение"
        echo "Пример: az.az"
        exit 1
    fi
    
    # Проверка длины имени файла
    if [ ${#FILE_NAME} -gt 7 ]; then
        echo "Ошибка: для имени файла не более 7 символов"
        exit 1
    fi
    
    # Проверка длины расширения
    if [ ${#FILE_EXT} -gt 3 ]; then
        echo "Ошибка: для расширения не более 3 символов"
        exit 1
    fi
    
    # Проверка, что буквы для имени файла только английские
    if [[ ! "$FILE_NAME" =~ ^[a-zA-Z]+$ ]]; then
        echo "Ошибка: буквы для имени файла должны быть английскими"
        exit 1
    fi
    
    # Проверка, что буквы для расширения только английские
    if [[ ! "$FILE_EXT" =~ ^[a-zA-Z]+$ ]]; then
        echo "Ошибка: расширение должно содержать только английские буквы"
        exit 1
    fi
    
    # Проверка формата размера файла
    if [[ ! "$FILE_SIZE" =~ ^[0-9]+Mb$ ]]; then
        echo "Ошибка: размер файла должен быть в формате XMb, где X - число"
        echo "Пример: 3Mb"
        exit 1
    fi
    
    # Извлекаем число из размера
    local size_num=$(echo $FILE_SIZE | sed 's/Mb//')
    
    # Проверка размера файла (не более 100 Mb)
    if [ $size_num -le 0 ] || [ $size_num -gt 100 ]; then
        echo "Ошибка: размер файла должен быть от 1 до 100 Mb"
        exit 1
    fi
}
